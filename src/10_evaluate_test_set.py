"""
Evaluate all six trained model experiments on the held-out test set.

Inputs:
    data/processed/test.csv
    data/processed/test_preprocessed.csv
    results/models/raw_*.joblib
    results/models/preprocessed_*.joblib

Outputs:
    results/metrics/test_set_metrics.csv
    results/metrics/test_set_evaluation_summary.txt
    results/figures/confusion_matrix_<experiment>_<model>.png

Test metrics are for final reporting only; do not use them for model tuning.
"""

from pathlib import Path
import sys
import warnings

import joblib
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    confusion_matrix,
    ConfusionMatrixDisplay,
)

ROOT_DIR = Path(__file__).resolve().parents[1]
PROCESSED_DIR = ROOT_DIR / "data" / "processed"
MODELS_DIR = ROOT_DIR / "results" / "models"
METRICS_DIR = ROOT_DIR / "results" / "metrics"
FIGURES_DIR = ROOT_DIR / "results" / "figures"
TARGET_COLUMN = "Success"

EXPERIMENTS = [
    ("Raw features", "raw", "raw_logistic_regression.joblib", "Logistic Regression"),
    ("Raw features", "raw", "raw_random_forest.joblib", "Random Forest"),
    ("Raw features", "raw", "raw_xgboost.joblib", "XGBoost"),
    ("Preprocessed features", "preprocessed", "preprocessed_logistic_regression.joblib", "Logistic Regression"),
    ("Preprocessed features", "preprocessed", "preprocessed_random_forest.joblib", "Random Forest"),
    ("Preprocessed features", "preprocessed", "preprocessed_xgboost.joblib", "XGBoost"),
]


def stop(message):
    print(f"ERROR: {message}")
    sys.exit(1)


def read_test(path):
    if not path.exists():
        stop(f"Test file not found: {path}")
    frame = pd.read_csv(path, index_col=False, low_memory=False)
    if TARGET_COLUMN not in frame.columns:
        stop(f"Target column '{TARGET_COLUMN}' missing from {path.name}.")
    if frame[TARGET_COLUMN].isna().any():
        stop(f"Missing target values in {path.name}.")
    return frame


def sanitize_columns(columns):
    """Apply the same XGBoost-safe naming rule used during model training."""
    result = []
    used = set()
    for index, name in enumerate(columns):
        safe = str(name).replace("[", "_").replace("]", "_")
        safe = safe.replace("<", "_").replace(">", "_")
        base = safe or f"feature_{index}"
        candidate = base
        suffix = 1
        while candidate in used:
            candidate = f"{base}_{suffix}"
            suffix += 1
        used.add(candidate)
        result.append(candidate)
    return result


def get_predictions(experiment_key, model_filename, model_name, raw_test, preprocessed_test):
    model_path = MODELS_DIR / model_filename
    if not model_path.exists():
        stop(f"Trained model not found: {model_path}")
    bundle = joblib.load(model_path)
    model = bundle["model"]

    if experiment_key == "raw":
        feature_columns = bundle["feature_columns"]
        missing = [column for column in feature_columns if column not in raw_test.columns]
        if missing:
            stop(f"Raw test data is missing columns required by {model_name}: {missing[:10]}")
        x = raw_test[feature_columns].copy()
        x_ready = bundle["preprocessor"].transform(x)
        y = raw_test[TARGET_COLUMN].astype("int8").to_numpy()
    else:
        # For the preprocessed experiments, the training script saved the exact
        # feature schema. Use the original feature names when selecting columns,
        # then apply the same sanitized names used for model fitting.
        original_columns = bundle.get("original_feature_columns")
        model_columns = bundle.get("feature_columns")

        if original_columns is not None:
            missing = [column for column in original_columns if column not in preprocessed_test.columns]
            if missing:
                stop(
                    f"Preprocessed test file is missing {len(missing)} feature column(s) "
                    f"needed by {model_name}. First missing names: {missing[:5]}. "
                    "The train and test preprocessed files may have been generated by "
                    "different versions of the preprocessing script."
                )
            x = preprocessed_test[original_columns].copy()
            if model_columns is not None and len(model_columns) == len(original_columns):
                x.columns = model_columns
            elif model_name == "XGBoost":
                x.columns = sanitize_columns(original_columns)
        else:
            # Older Logistic Regression/Random Forest bundles store the column
            # names exactly as read from the preprocessed CSV.
            missing = [column for column in model_columns if column not in preprocessed_test.columns]
            if missing:
                stop(
                    f"Preprocessed test file is missing {len(missing)} feature column(s) "
                    f"needed by {model_name}. First missing names: {missing[:5]}."
                )
            x = preprocessed_test[model_columns].copy()

        y = preprocessed_test[TARGET_COLUMN].astype("int8").to_numpy()
        x_ready = x

    predictions = model.predict(x_ready)
    probabilities = model.predict_proba(x_ready)[:, 1]
    return y, predictions, probabilities


def main():
    METRICS_DIR.mkdir(parents=True, exist_ok=True)
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)

    raw_test = read_test(PROCESSED_DIR / "test.csv")
    preprocessed_test = read_test(PROCESSED_DIR / "test_preprocessed.csv")

    if len(raw_test) != len(preprocessed_test):
        stop("Raw and preprocessed test sets have different row counts.")
    if not np.array_equal(
        raw_test[TARGET_COLUMN].astype("int8").to_numpy(),
        preprocessed_test[TARGET_COLUMN].astype("int8").to_numpy(),
    ):
        stop("Raw and preprocessed test target sequences do not match.")

    result_rows = []
    report_lines = [
        "STEAM GAMES SUCCESS PREDICTION — HELD-OUT TEST EVALUATION",
        "=" * 66,
        f"Test rows: {len(raw_test):,}",
        "Target: Success (0 = Not Success, 1 = Success)",
        "These metrics are from the held-out test set.",
        "",
        "TEST METRICS",
        "-" * 66,
    ]

    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", category=UserWarning)
        for experiment_label, experiment_key, model_filename, model_name in EXPERIMENTS:
            print(f"Evaluating {model_name} — {experiment_label}...")
            y, predictions, probabilities = get_predictions(
                experiment_key, model_filename, model_name, raw_test, preprocessed_test
            )
            metrics = {
                "experiment": experiment_label,
                "model": model_name,
                "accuracy": accuracy_score(y, predictions),
                "precision": precision_score(y, predictions, zero_division=0),
                "recall": recall_score(y, predictions, zero_division=0),
                "f1": f1_score(y, predictions, zero_division=0),
                "roc_auc": roc_auc_score(y, probabilities),
            }
            result_rows.append(metrics)

            matrix = confusion_matrix(y, predictions, labels=[0, 1])
            matrix_path = FIGURES_DIR / (
                f"confusion_matrix_{experiment_key}_{model_name.lower().replace(' ', '_')}.png"
            )
            fig, ax = plt.subplots(figsize=(6, 5))
            ConfusionMatrixDisplay(
                confusion_matrix=matrix,
                display_labels=["Not Success", "Success"],
            ).plot(ax=ax, values_format="d", colorbar=False)
            ax.set_title(f"{model_name} — {experiment_label}\nTest Confusion Matrix")
            fig.tight_layout()
            fig.savefig(matrix_path, dpi=160, bbox_inches="tight")
            plt.close(fig)

            report_lines.append(
                f"{model_name} — {experiment_label}: "
                + ", ".join(f"{key}={metrics[key]:.4f}" for key in
                            ["accuracy", "precision", "recall", "f1", "roc_auc"])
            )
            report_lines.append(
                f"  Confusion matrix [[TN, FP], [FN, TP]]: "
                f"[[{matrix[0, 0]}, {matrix[0, 1]}], [{matrix[1, 0]}, {matrix[1, 1]}]]"
            )

    metrics_file = METRICS_DIR / "test_set_metrics.csv"
    pd.DataFrame(result_rows).to_csv(metrics_file, index=False)

    best_f1 = max(result_rows, key=lambda row: row["f1"])
    report_lines.extend([
        "",
        "HIGHEST TEST F1 (DESCRIPTIVE ONLY)",
        "-" * 66,
        f"Model: {best_f1['model']}",
        f"Experiment: {best_f1['experiment']}",
        f"F1-score: {best_f1['f1']:.4f}",
        "",
        "METHODOLOGY NOTE",
        "-" * 66,
        "Use validation metrics for model selection. Do not tune on this test set and then report it as an unbiased final estimate.",
    ])
    report_file = METRICS_DIR / "test_set_evaluation_summary.txt"
    report_file.write_text("\n".join(report_lines) + "\n", encoding="utf-8")

    print("\nHeld-out test evaluation completed successfully.")
    print(pd.DataFrame(result_rows).to_string(index=False, formatters={
        metric: "{:.4f}".format for metric in
        ["accuracy", "precision", "recall", "f1", "roc_auc"]
    }))
    print(f"\nMetrics saved to: {metrics_file}")
    print(f"Summary saved to: {report_file}")
    print(f"Confusion matrices saved in: {FIGURES_DIR}")


if __name__ == "__main__":
    main()
